function fromCrop(path: string, left: number, top: number, zoom: number) {
  let coordinate = 0;
  return path.replace(/-?\d+(?:\.\d+)?/g, value =>
    (Number(value) / zoom + (coordinate++ % 2 === 0 ? left : top)).toFixed(3));
}
